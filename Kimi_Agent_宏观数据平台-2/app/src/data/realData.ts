// 获取完整的数据数组（真实数据 + 插值填充）
export function getFullData(realData: Record<string, number>, allMonths: string[]): number[] {
  return allMonths.map(m => {
    if (realData[m] !== undefined) return realData[m];
    // 对于缺失的数据，使用前后真实数据点线性插值
    const idx = allMonths.indexOf(m);
    let prevIdx = idx - 1;
    let nextIdx = idx + 1;
    while (prevIdx >= 0 && realData[allMonths[prevIdx]] === undefined) prevIdx--;
    while (nextIdx < allMonths.length && realData[allMonths[nextIdx]] === undefined) nextIdx++;
    
    if (prevIdx >= 0 && nextIdx < allMonths.length) {
      const prevVal = realData[allMonths[prevIdx]];
      const nextVal = realData[allMonths[nextIdx]];
      const ratio = (idx - prevIdx) / (nextIdx - prevIdx);
      return Number((prevVal + (nextVal - prevVal) * ratio).toFixed(1));
    }
    return 0;
  });
}
